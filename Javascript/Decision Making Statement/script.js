let mark = 191;

if (mark > 90) {
  console.log(`Grade A`);
} else if (mark >= 75) {
  console.log(`Grade B`);
} else if (mark >= 50) {
  console.log(`Grade C`);
} else if (mark >= 35) {
  console.log(`Grade D`);
} else if (mark >= 0) {
  console.log(`Fail`);
} else {
  console.log(`invalid number`);
}
